//go:build ignore

// Development-only generator. The production encoder uses typed field access,
// preserving encoding/json's field order, names and omitempty semantics.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"strconv"
	"strings"

	run "github.com/muidea/workorch/internal/modules/blocks/run/pkg/models"
)

func main() {
	output := flag.String("output", "run_physical_json_generated.go", "output Go file")
	flag.Parse()
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by scripts/generate-run-physical-json.go; DO NOT EDIT.\n\npackage file")
	fmt.Fprintln(&out, "import run \"github.com/muidea/workorch/internal/modules/blocks/run/pkg/models\"")
	fmt.Fprintln(&out, "func (e *runPhysicalJSONEncoder) run(v *run.Run) { e.text(\"{\"); first := true")
	typ := reflect.TypeOf(run.Run{})
	for i := 0; i < typ.NumField(); i++ {
		field := typ.Field(i)
		if !field.IsExported() || field.Anonymous {
			panic("unsupported physical Run field: " + field.Name)
		}
		tag := strings.Split(field.Tag.Get("json"), ",")
		if tag[0] == "-" {
			continue
		}
		name := tag[0]
		if name == "" {
			name = field.Name
		}
		optional := len(tag) > 1
		if optional {
			if len(tag) != 2 || tag[1] != "omitempty" || field.Type.Kind() != reflect.Slice {
				panic("unsupported Run JSON tag: " + field.Name)
			}
			fmt.Fprintf(&out, "if len(v.%s) != 0 {\n", field.Name)
		}
		fmt.Fprintf(&out, "if !first { e.text(\",\") }; first = false; e.text(%s)\n", strconv.Quote(strconv.Quote(name)+":"))
		method := "value"
		if field.Name == "RuntimeState" {
			fmt.Fprintln(&out, "e.state(v)")
		} else {
			fmt.Fprintf(&out, "e.%s(v.%s)\n", method, field.Name)
		}
		if optional {
			fmt.Fprintln(&out, "}")
		}
	}
	fmt.Fprintln(&out, "e.text(\"}\")\n}")
	code, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(*output, code, 0o644); err != nil {
		panic(err)
	}
}
