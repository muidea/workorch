// RuntimeRepairClosure is the immutable, focus-scoped repair objective derived
// by SM-2 from an assessed gap.  It deliberately carries only neutral facts:
// the gap identity, evidence baseline, coverage, evidence family and already
// grounded targets.  It does not select an action or infer an operation.
//
// A state-change and its mandatory follow-up validation retain the same
// closure ID.  This prevents a validation-gap repair from degrading into an
// unrelated durable change between sealed dispatches.
type RuntimeRepairClosure struct {
	ID                       string
	GapSignature             string
	BaselineEvidenceRevision string
	CoverageWorkItemIDs      []common.CoverageWorkItemID
	// RequiredEvidenceKinds is generated by the SM-2 owner for this repair
	// closure. It is deliberately separate from an assessment observation's
	// claimed missing kinds.
	RequiredEvidenceKinds             []string
	GroundedTargetRefs                []string
	RequireValidationAfterStateChange bool
}

func (c RuntimeRepairClosure) Normalized() RuntimeRepairClosure {
	c.ID = strings.TrimSpace(c.ID)
	c.GapSignature = strings.TrimSpace(c.GapSignature)
	c.BaselineEvidenceRevision = strings.TrimSpace(c.BaselineEvidenceRevision)
	c.CoverageWorkItemIDs = normalizeCoverageWorkItemIDs(c.CoverageWorkItemIDs)
	c.RequiredEvidenceKinds = normalizeStrings(c.RequiredEvidenceKinds)
	c.GroundedTargetRefs = normalizeStrings(c.GroundedTargetRefs)
	return c
}

func (c RuntimeRepairClosure) Validate() error {
	c = c.Normalized()
	if c.ID == "" || c.GapSignature == "" || c.BaselineEvidenceRevision == "" {
		return fmt.Errorf("repair closure requires id, gap signature and baseline evidence revision")
	}
	if len(c.CoverageWorkItemIDs) == 0 {
		return fmt.Errorf("repair closure requires coverage work items")
	}
	if want := StableRuntimeRepairClosureID(c); c.ID != want {
		return fmt.Errorf("repair closure identity mismatch")
	}
	return nil
}

func (c RuntimeRepairClosure) Clone() RuntimeRepairClosure { return c.Normalized() }

// StableRuntimeRepairClosureID is a pure value identity.  The Orchestrator is
// the only component allowed to decide when a new closure is created.
func StableRuntimeRepairClosureID(value RuntimeRepairClosure) string {
	value = value.Normalized()
	h := sha256.New()
	writeHashString(h, value.GapSignature)
	writeHashString(h, value.BaselineEvidenceRevision)
	coverage := make([]string, 0, len(value.CoverageWorkItemIDs))
	for _, id := range value.CoverageWorkItemIDs {
		coverage = append(coverage, string(id))
	}
	writeHashStrings(h, coverage)
	writeHashStrings(h, value.RequiredEvidenceKinds)
	writeHashStrings(h, value.GroundedTargetRefs)
	if value.RequireValidationAfterStateChange {
		writeHashString(h, "require-validation")
	}
	return "repair-closure-" + hex.EncodeToString(h.Sum(nil))[:20]
}

func SameRuntimeRepairClosure(left, right *RuntimeRepairClosure) bool {
	if left == nil || right == nil {
		return left == right
	}
	l, r := left.Normalized(), right.Normalized()
	return l.ID == r.ID && l.GapSignature == r.GapSignature &&
		l.BaselineEvidenceRevision == r.BaselineEvidenceRevision &&
		l.RequireValidationAfterStateChange == r.RequireValidationAfterStateChange &&
		sameCoverageWorkItemIDs(l.CoverageWorkItemIDs, r.CoverageWorkItemIDs) &&
		sameStrings(l.RequiredEvidenceKinds, r.RequiredEvidenceKinds) &&
		sameStrings(l.GroundedTargetRefs, r.GroundedTargetRefs)
}

// RuntimeGovernanceKind unifies decision/approval/configuration/external dependency (RVC-R11 prep).
type RuntimeGovernanceKind string

const (
	GovernanceDecision      RuntimeGovernanceKind = "decision"
	GovernanceApproval      RuntimeGovernanceKind = "approval"
	GovernanceConfiguration RuntimeGovernanceKind = "configuration"
	GovernanceExternal      RuntimeGovernanceKind = "external_dependency"
)

// RuntimeGovernanceRequirement is returned by owners before side effects when
// approval/decision/config/external dependency is required (INV-06).
type RuntimeGovernanceRequirement struct {
	Kind            RuntimeGovernanceKind
	SubjectRef      string
	Reason          string
	RequestedAction string
	RiskLevel       string
}

func (k RuntimeGovernanceKind) Normalized() RuntimeGovernanceKind {
	return RuntimeGovernanceKind(strings.TrimSpace(string(k)))
}

func ValidRuntimeGovernanceKind(kind RuntimeGovernanceKind) bool {
	switch kind.Normalized() {
	case GovernanceDecision, GovernanceApproval, GovernanceConfiguration, GovernanceExternal:
		return true
	default:
		return false
	}
}

func (r RuntimeGovernanceRequirement) Normalized() RuntimeGovernanceRequirement {
	r.Kind = r.Kind.Normalized()
	r.SubjectRef = strings.TrimSpace(r.SubjectRef)
	r.Reason = strings.TrimSpace(r.Reason)
	r.RequestedAction = strings.TrimSpace(r.RequestedAction)
	r.RiskLevel = strings.TrimSpace(r.RiskLevel)
	return r
}

func (r RuntimeGovernanceRequirement) Validate() error {
	r = r.Normalized()
	if !ValidRuntimeGovernanceKind(r.Kind) {
		return fmt.Errorf("governance requirement has invalid kind %q", r.Kind)
	}
	if r.SubjectRef == "" || r.Reason == "" {
		return fmt.Errorf("governance requirement requires subject ref and reason")
	}
	return nil
}

func (r RuntimeGovernanceRequirement) Clone() RuntimeGovernanceRequirement {
	return r.Normalized()
}

// RuntimeTerminationKind is the administrative terminal kind for SM-1 cancel/supersede.
type RuntimeTerminationKind string

const (
	RuntimeTerminationCancelled  RuntimeTerminationKind = "cancelled"
	RuntimeTerminationSuperseded RuntimeTerminationKind = "superseded"
)

// RuntimeTerminationRecord is CAS-persisted before SM-1 projects cancelled/superseded (INV-08).
// completed/failed remain SM-2 sealed terminal only and do not use this record.
type RuntimeTerminationRecord struct {
	Kind        RuntimeTerminationKind
	RequestedBy string
	Reason      string
	Revision    uint64
	RequestedAt string
}

func (k RuntimeTerminationKind) Normalized() RuntimeTerminationKind {
	return RuntimeTerminationKind(strings.TrimSpace(string(k)))
}

func ValidRuntimeTerminationKind(kind RuntimeTerminationKind) bool {
	switch kind.Normalized() {
	case RuntimeTerminationCancelled, RuntimeTerminationSuperseded:
		return true
	default:
		return false
	}
}

func (r RuntimeTerminationRecord) Normalized() RuntimeTerminationRecord {
	r.Kind = r.Kind.Normalized()
	r.RequestedBy = strings.TrimSpace(r.RequestedBy)
	r.Reason = strings.TrimSpace(r.Reason)
	r.RequestedAt = strings.TrimSpace(r.RequestedAt)
	return r
}

func (r RuntimeTerminationRecord) Validate() error {
	r = r.Normalized()
	if !ValidRuntimeTerminationKind(r.Kind) {
		return fmt.Errorf("termination record has invalid kind %q", r.Kind)
	}
	if r.Reason == "" {
		return fmt.Errorf("termination record requires reason")
	}
	if r.Revision == 0 {
		return fmt.Errorf("termination record requires revision")
	}
	return nil
}

func (r RuntimeTerminationRecord) Clone() RuntimeTerminationRecord {
	return r.Normalized()
}

// RuntimeRepairTrigger classifies why a repair directive was created.
type RuntimeRepairTrigger string

const (
	RuntimeRepairTriggerRejectedValidation  RuntimeRepairTrigger = "rejected_validation"
	RuntimeRepairTriggerAssessmentGap       RuntimeRepairTrigger = "assessment_gap"
	RuntimeRepairTriggerExecutionRejected   RuntimeRepairTrigger = "execution_rejected"
	RuntimeRepairTriggerCandidateInfeasible RuntimeRepairTrigger = "candidate_infeasible"
	RuntimeRepairTriggerEffectMismatch      RuntimeRepairTrigger = "effect_mismatch"
	RuntimeRepairTriggerMissingEvidence     RuntimeRepairTrigger = "missing_evidence"
)

// RuntimeRepairDirective is the single persisted canonical-state authority for a focus (INV-05).
// Candidate renderer, anti-replay, and owners must obey RequiredState; they cannot switch it.
type RuntimeRepairDirective struct {
	ID                        string
	FocusID                   string
	Trigger                   RuntimeRepairTrigger
	CurrentFailure            *FailureFact
	RequiredState             ConvergenceState
	RequiredEffectScopes      []RuntimeEffectScope
	RequiredEvidenceKinds     []string
	AllowedOperationKinds     []string
	RejectedOperationShapes   []RuntimeRejectedOperationShape
	NoProgressOperationShapes []RuntimeRejectedOperationShape
	CoverageWorkItemIDs       []common.CoverageWorkItemID
	TargetRefs                []string
	// Closure is optional only for persisted directives created before repair
	// closure support. New SM-2 repair directives must carry it.
	Closure                    *RuntimeRepairClosure
	SupersedesEvidenceRevision string
	RepairAttempt              int
}

func (t RuntimeRepairTrigger) Normalized() RuntimeRepairTrigger {
	return RuntimeRepairTrigger(strings.TrimSpace(string(t)))
}

func ValidRuntimeRepairTrigger(trigger RuntimeRepairTrigger) bool {
	switch trigger.Normalized() {
	case RuntimeRepairTriggerRejectedValidation, RuntimeRepairTriggerAssessmentGap,
		RuntimeRepairTriggerExecutionRejected, RuntimeRepairTriggerCandidateInfeasible, RuntimeRepairTriggerEffectMismatch,
		RuntimeRepairTriggerMissingEvidence:
		return true
	default:
		return false
	}
}

func (d RuntimeRepairDirective) Normalized() RuntimeRepairDirective {
	d.ID = strings.TrimSpace(d.ID)
	d.FocusID = strings.TrimSpace(d.FocusID)
	d.Trigger = d.Trigger.Normalized()
	if d.CurrentFailure != nil {
		failure := d.CurrentFailure.Normalized()
		d.CurrentFailure = &failure
	}
	d.RequiredState = ConvergenceState(strings.TrimSpace(string(d.RequiredState)))
	d.RequiredEffectScopes = NormalizeRuntimeEffectScopes(d.RequiredEffectScopes)
	d.RequiredEvidenceKinds = normalizeStrings(d.RequiredEvidenceKinds)
	d.AllowedOperationKinds = normalizeStrings(d.AllowedOperationKinds)
	d.RejectedOperationShapes = NormalizeRuntimeRejectedOperationShapes(d.RejectedOperationShapes)
	d.NoProgressOperationShapes = NormalizeRuntimeRejectedOperationShapes(d.NoProgressOperationShapes)
	d.CoverageWorkItemIDs = normalizeCoverageWorkItemIDs(d.CoverageWorkItemIDs)
	d.TargetRefs = normalizeStrings(d.TargetRefs)
	if d.Closure != nil {
		closure := d.Closure.Normalized()
		d.Closure = &closure
	}
	d.SupersedesEvidenceRevision = strings.TrimSpace(d.SupersedesEvidenceRevision)
	return d
}

func (d RuntimeRepairDirective) Validate() error {
	d = d.Normalized()
	if d.ID == "" || d.FocusID == "" {
		return fmt.Errorf("repair directive requires id and focus id")
	}
	if !ValidRuntimeRepairTrigger(d.Trigger) {
		return fmt.Errorf("repair directive has invalid trigger %q", d.Trigger)
	}
	switch d.RequiredState {
	case ConvergenceStateNeedStateChange, ConvergenceStateNeedValidation, ConvergenceStateNeedGovernance:
		// allowed
	default:
		return fmt.Errorf("repair directive required state %q is not a repairable state", d.RequiredState)
	}
	if err := ValidateEffectScopesCompatibleWithState(d.RequiredState, d.RequiredEffectScopes); err != nil {
		return fmt.Errorf("repair directive effect scopes: %w", err)
	}
	if d.RepairAttempt < 0 {
		return fmt.Errorf("repair directive attempt cannot be negative")
	}
	if d.CurrentFailure != nil {
		if d.CurrentFailure.Class == "" || d.CurrentFailure.Message == "" {
			return fmt.Errorf("repair directive current failure requires class and message")
		}
		if err := ValidateRuntimeFailureTargetObservationBinding(*d.CurrentFailure); err != nil {
			return fmt.Errorf("repair directive current failure target observation: %w", err)
		}
	}
	if d.Closure != nil {
		if err := d.Closure.Validate(); err != nil {
			return fmt.Errorf("repair directive closure: %w", err)
		}
		if !sameCoverageWorkItemIDs(d.CoverageWorkItemIDs, d.Closure.CoverageWorkItemIDs) {
			return fmt.Errorf("repair directive coverage does not match repair closure")
		}
		if len(d.TargetRefs) > 0 && !sameStrings(d.TargetRefs, d.Closure.GroundedTargetRefs) {
			return fmt.Errorf("repair directive targets do not match repair closure")
		}
	}
	return nil
}

func (d RuntimeRepairDirective) Clone() RuntimeRepairDirective {
	ret := d.Normalized()
	if d.CurrentFailure != nil {
		failure := ret.CurrentFailure.Clone()
		ret.CurrentFailure = &failure
	}
	if d.Closure != nil {
		closure := d.Closure.Clone()
		ret.Closure = &closure
	}
	if len(ret.RejectedOperationShapes) > 0 {
		shapes := make([]RuntimeRejectedOperationShape, len(ret.RejectedOperationShapes))
		copy(shapes, ret.RejectedOperationShapes)
		ret.RejectedOperationShapes = shapes
	}
	if len(ret.NoProgressOperationShapes) > 0 {
		shapes := make([]RuntimeRejectedOperationShape, len(ret.NoProgressOperationShapes))
		copy(shapes, ret.NoProgressOperationShapes)
		ret.NoProgressOperationShapes = shapes
	}
	return ret
}

func SameRuntimeRepairDirective(left *RuntimeRepairDirective, right *RuntimeRepairDirective) bool {
	if left == nil && right == nil {
		return true
	}
	if left == nil || right == nil {
		return false
	}
	l := left.Normalized()
	r := right.Normalized()
	if l.ID != r.ID || l.FocusID != r.FocusID || l.Trigger != r.Trigger || l.RequiredState != r.RequiredState ||
		l.SupersedesEvidenceRevision != r.SupersedesEvidenceRevision || l.RepairAttempt != r.RepairAttempt {
		return false
	}
	if !SameRuntimeRepairClosure(l.Closure, r.Closure) {
		return false
	}
	if !SameRuntimeEffectScopes(l.RequiredEffectScopes, r.RequiredEffectScopes) ||
		!sameStrings(l.RequiredEvidenceKinds, r.RequiredEvidenceKinds) ||
		!sameStrings(l.AllowedOperationKinds, r.AllowedOperationKinds) ||
		!sameCoverageWorkItemIDs(l.CoverageWorkItemIDs, r.CoverageWorkItemIDs) ||
		!sameStrings(l.TargetRefs, r.TargetRefs) {
		return false
	}
	if (l.CurrentFailure == nil) != (r.CurrentFailure == nil) {
		return false
	}
	if l.CurrentFailure != nil {
		if l.CurrentFailure.Class != r.CurrentFailure.Class || l.CurrentFailure.Code != r.CurrentFailure.Code ||
			l.CurrentFailure.Signature != r.CurrentFailure.Signature || l.CurrentFailure.Message != r.CurrentFailure.Message ||
			!sameStrings(l.CurrentFailure.TargetRefs, r.CurrentFailure.TargetRefs) ||
			!sameRuntimeFailureTargetObservation(l.CurrentFailure.TargetObservation, r.CurrentFailure.TargetObservation) ||
			!sameValidationFailureDiagnostic(l.CurrentFailure.ValidationDiagnostic, r.CurrentFailure.ValidationDiagnostic) ||
			!sameRuntimeValidationFailureObservation(l.CurrentFailure.ValidationFailureObservation, r.CurrentFailure.ValidationFailureObservation) {
			return false
		}
	}
	if len(l.RejectedOperationShapes) != len(r.RejectedOperationShapes) {
		return false
	}
	for idx := range l.RejectedOperationShapes {
		if l.RejectedOperationShapes[idx].Hash != r.RejectedOperationShapes[idx].Hash {
			return false
		}
	}
	if len(l.NoProgressOperationShapes) != len(r.NoProgressOperationShapes) {
		return false
	}
	for idx := range l.NoProgressOperationShapes {
		if l.NoProgressOperationShapes[idx].Hash != r.NoProgressOperationShapes[idx].Hash {
			return false
		}
	}
	return true
}

func sameRuntimeValidationFailureObservation(left *RuntimeValidationFailureObservation, right *RuntimeValidationFailureObservation) bool {
	if left == nil && right == nil {
		return true
	}
	if left == nil || right == nil {
		return false
	}
	return SameRuntimeValidationFailureObservation(*left, *right)
}

func sameRuntimeFailureTargetObservation(left *RuntimeFailureTargetObservation, right *RuntimeFailureTargetObservation) bool {
	if left == nil && right == nil {
		return true
	}
	if left == nil || right == nil {
		return false
	}
	l := left.Normalized()
	r := right.Normalized()
	return l.OwnerModuleID == r.OwnerModuleID && l.SubjectRef == r.SubjectRef &&
		l.TargetRole == r.TargetRole && l.ObservedRevision == r.ObservedRevision &&
		l.DiagnosticClass == r.DiagnosticClass && l.ContentHash == r.ContentHash &&
		sameStrings(l.TargetRefs, r.TargetRefs) && sameStrings(l.EvidenceRefs, r.EvidenceRefs)
}
