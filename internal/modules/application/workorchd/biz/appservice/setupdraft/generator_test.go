func TestEventHubGeneratorUsesLLMCommandEvent(t *testing.T) {
	rawHub := magicevent.NewHub(16)
	var seenRequest llmmodels.ProviderRequest
	observer := magicevent.NewSimpleObserver(llmevents.CommandDestination, rawHub)
	observer.Subscribe(llmevents.TopicLLMCommandCompleteProvider, func(ev magicevent.Event, result magicevent.Result) {
		cmd, ok := ev.Data().(llmevents.CompleteProviderCommand)
		if !ok {
			t.Fatalf("provider command = %#v, want CompleteProviderCommand", ev.Data())
		}
		request, err := cmd.Request.ToModel()
		if err != nil {
			t.Fatalf("provider request mapping: %v", err)
		}
		seenRequest = request
		result.Set(llmevents.LLMCommandResult{
			Completion: &llmevents.ProviderCompletionData{
				Content: `{"draft":{"goalText":"Generated goal","doDItems":["Generated DoD"],"confidence":"high"}}`,
			},
		}, nil)
	})
	defer observer.Unsubscribe(llmevents.TopicLLMCommandCompleteProvider)
	time.Sleep(10 * time.Millisecond)

	draft, err := EventHubGenerator{CommandHub: rawHub}.GenerateWorkspaceSetupDraft(context.Background(), GenerationRequest{
		Template:       workorchmanagementcontract.WorkspaceTemplate{ID: "template-001"},
		DialogLanguage: "zh-CN",
		Messages:       []Message{{Role: "user", Content: "Create a workspace"}},
	})
	if err != nil {
		t.Fatalf("GenerateWorkspaceSetupDraft: %v", err)
	}
	if draft.GoalText != "Generated goal" || !reflect.DeepEqual(draft.DoDItems, []string{"Generated DoD"}) {
		t.Fatalf("draft = %+v, want provider response parsed", draft)
	}
	if seenRequest.Kind != "workspace/setup_draft" || seenRequest.Schema != WorkspaceSetupDraftSchemaName || seenRequest.DialogLanguage != "zh-CN" {
		t.Fatalf("provider request = %+v, want workspace setup draft request", seenRequest)
	}
	if seenRequest.TraceRefs["templateId"] != "template-001" {
		t.Fatalf("trace refs = %+v, want template id", seenRequest.TraceRefs)
	}
	if seenRequest.PromptContext == nil || len(seenRequest.PromptContext.Sections) != 2 {
		t.Fatalf("prompt context = %+v, want typed setup contract and request sections", seenRequest.PromptContext)
	}
}

func TestEventHubGeneratorUsesLLMOwnerFrozenDefaultTarget(t *testing.T) {
	ctx := context.Background()
	var requestedModel string
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/v1/models":
			_ = json.NewEncoder(w).Encode(map[string]any{
				"object": "list",
				"data": []map[string]any{{
					"id": "model-a", "supported_endpoints": []string{"/v1/responses"},
					"contextWindowTokens": 8192, "maxOutputTokens": 1024,
				}},
			})
		case "/v1/responses":
			var request struct {
				Model string `json:"model"`
			}
			if err := json.NewDecoder(r.Body).Decode(&request); err != nil {
				t.Errorf("decode provider request: %v", err)
			}
			requestedModel = request.Model
			w.Header().Set("Content-Type", "text/event-stream")
			payload, _ := json.Marshal(map[string]any{
				"type": "response.completed",
				"response": map[string]any{
					"status":      "completed",
					"output_text": `{"draft":{"goalText":"Generated by owner","doDItems":["Owner path"]}}`,
				},
			})
			_, _ = fmt.Fprintf(w, "data: %s\n\n", payload)
		default:
			http.NotFound(w, r)
		}
	}))
	defer server.Close()

	configured := workorchconfig.DefaultLLMConfig()
	configured.AIProxy.BaseURL = server.URL
	configured.DefaultChat = workorchconfig.ProviderModelTargetConfig{ProviderID: workorchconfig.BuiltinAIProxyProviderID, ModelID: "model-a"}
	hub := magicevent.NewHub(16)
	t.Cleanup(func() { hub.Terminate(ctx) })
	owner, err := llmbiz.New(hub, nil, llmbiz.Dependencies{LoadLLMConfig: func() (workorchconfig.LLMConfig, error) {
		return configured, nil
	}})
	if err != nil {
		t.Fatal(err)
	}
	if err := owner.Start(); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { owner.Teardown(ctx) })
	auditObserver := magicevent.NewSimpleObserver("/llm/consumers/setup-draft-audit-test", hub)
	audits := make(chan llmevents.LLMUsageRecordedData, 1)
	auditObserver.Subscribe(llmevents.TopicLLMUsageRecorded, func(event magicevent.Event, _ magicevent.Result) {
		if data, ok := event.Data().(llmevents.LLMUsageRecordedData); ok {
			audits <- data
		}
	})
	t.Cleanup(func() { auditObserver.Unsubscribe(llmevents.TopicLLMUsageRecorded) })

	configured.DefaultChat.ModelID = "model-b"
	draft, err := (EventHubGenerator{CommandHub: hub}).GenerateWorkspaceSetupDraft(ctx, GenerationRequest{
		Template: workorchmanagementcontract.WorkspaceTemplate{ID: "template-001"},
		Messages: []Message{{Role: "user", Content: "Create a workspace"}},
	})
	if err != nil {
		t.Fatalf("GenerateWorkspaceSetupDraft through real owner: %v", err)
	}
	if requestedModel != "model-a" || draft.GoalText != "Generated by owner" {
		t.Fatalf("owner target=%q draft=%+v, want frozen model-a completion", requestedModel, draft)
	}
	select {
	case audit := <-audits:
		if audit.Operation != workorchconfig.LLMOperationResponses || audit.Target.ModelID != "model-a" || audit.WorkspaceID != "" || audit.RunID != "" || !audit.ProviderSubmitted || audit.ResponseBytes == 0 {
			t.Fatalf("setup draft provider audit = %+v", audit)
		}
	case <-time.After(2 * time.Second):
		t.Fatal("setup draft provider call did not publish usage audit")
	}
}
