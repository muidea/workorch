package server

// applicationOperationsFromPorts converts the public, typed injection shape
// into the private promoted callbacks used by handlers. The conversion is
// intentionally shallow: callbacks remain owned by the Biz/use-case layer.
func applicationOperationsFromPorts(ports ApplicationPorts) applicationOperations {
	return applicationOperations{
		workspaceOperations: workspaceOperations{
			validate:                              ports.Workspace.Validate,
			deleteWorkspace:                       ports.Workspace.DeleteWorkspace,
			readWorkspace:                         ports.Workspace.ReadWorkspace,
			readWorkspaceSnapshot:                 ports.Workspace.ReadWorkspaceSnapshot,
			readWorkspaceDetailSnapshot:           ports.Workspace.ReadWorkspaceDetailSnapshot,
			readProjectionSnapshot:                ports.Workspace.ReadProjectionSnapshot,
			readWorkspaceSoulBindings:             ports.Workspace.ReadWorkspaceSoulBindings,
			updateWorkspaceSoulBindings:           ports.Workspace.UpdateWorkspaceSoulBindings,
			updateWorkspaceLLMSelectionPort:       ports.Workspace.UpdateWorkspaceLLMSelection,
			listWorkspaces:                        ports.Workspace.ListWorkspaces,
			readStartupPreparation:                ports.Workspace.ReadStartupPreparation,
			checkStartupPreparation:               ports.Workspace.CheckStartupPreparation,
			initializeStartupPreparationResources: ports.Workspace.InitializeStartupPreparationResources,
			recoverStartupPreparationResources:    ports.Workspace.RecoverStartupPreparationResources,
			recoverStartupPreparation:             ports.Workspace.RecoverStartupPreparation,
		},
		definitionOperations: definitionOperations{
			authoring: DefinitionAuthoringPorts{
				Create: ports.Definition.CreateDefinitionAuthoring, Read: ports.Definition.ReadDefinitionAuthoring,
				Save: ports.Definition.SaveDefinitionAuthoring, Compile: ports.Definition.CompileDefinitionAuthoring,
				Confirm: ports.Definition.ConfirmDefinitionAuthoring, ReadDiagnostic: ports.Definition.ReadDefinitionAuthoringDiagnostic,
				ReadSuccessAudit:          ports.Definition.ReadDefinitionAuthoringSuccessAudit,
				ReadPreparationDiagnostic: ports.Definition.ReadDefinitionAuthoringPreparationDiagnostic,
			},
			readGoal:  ports.Definition.ReadGoal,
			listGoals: ports.Definition.ListGoals,
			readDoD:   ports.Definition.ReadDoD,
			listDoDs:  ports.Definition.ListDoDs,
		},
		runOperations: runOperations{
			readRun:                   ports.Run.ReadRun,
			readRunSnapshot:           ports.Run.ReadRunSnapshot,
			listRunSteps:              ports.Run.ListRunSteps,
			listRunToolCalls:          ports.Run.ListRunToolCalls,
			listRunRuntimeCheckpoints: ports.Run.ListRunRuntimeCheckpoints,
			listRunResults:            ports.Run.ListRunResults,
			listRunPatches:            ports.Run.ListRunPatches,
			listRunValidationResults:  ports.Run.ListRunValidationResults,
			listRunArtifacts:          ports.Run.ListRunArtifacts,
			readRunStatus:             ports.Run.ReadRunStatus,
			readRunObservability:      ports.Run.ReadRunObservability,
			readArtifactContent:       ports.Run.ReadArtifactContent,
			readRuntimeRawContent:     ports.Run.ReadRuntimeRawContent,
			readRunTaskProgress:       ports.Run.ReadRunTaskProgress,
			readRunContextBundle:      ports.Run.ReadRunContextBundle,
			readRunTaskDecompositions: ports.Run.ReadRunTaskDecompositions,
			listEventRecords:          ports.Run.ListEventRecords,
			listRuns:                  ports.Run.ListRuns,
		},
		governanceOperations: governanceOperations{
			listDecisions:         ports.Governance.ListDecisions,
			listDecisionPage:      ports.Governance.ListDecisionPage,
			readDecision:          ports.Governance.ReadDecision,
			resolveDecision:       ports.Governance.ResolveDecision,
			batchResolveDecisions: ports.Governance.BatchResolveDecisions,
			listApprovals:         ports.Governance.ListApprovals,
			listApprovalPage:      ports.Governance.ListApprovalPage,
			readApproval:          ports.Governance.ReadApproval,
			approveApproval:       ports.Governance.ApproveApproval,
			rejectApproval:        ports.Governance.RejectApproval,
			batchResolveApprovals: ports.Governance.BatchResolveApprovals,
		},
		registryOperations: registryOperations{
			listBuiltinDefaults:     ports.Registry.ListBuiltinDefaults,
			upgradeBuiltinDefault:   ports.Registry.UpgradeBuiltinDefault,
			createSoul:              ports.Registry.CreateSoul,
			updateSoul:              ports.Registry.UpdateSoul,
			deleteSoul:              ports.Registry.DeleteSoul,
			readSoul:                ports.Registry.ReadSoul,
			listSouls:               ports.Registry.ListSouls,
			createWorkspaceTemplate: ports.Registry.CreateWorkspaceTemplate,
			updateWorkspaceTemplate: ports.Registry.UpdateWorkspaceTemplate,
			deleteWorkspaceTemplate: ports.Registry.DeleteWorkspaceTemplate,
			listWorkspaceTemplates:  ports.Registry.ListWorkspaceTemplates,
			createSkill:             ports.Registry.CreateSkill,
			readSkill:               ports.Registry.ReadSkill,
			listSkills:              ports.Registry.ListSkills,
			createMCPServer:         ports.Registry.CreateMCPServer,
			updateMCPServer:         ports.Registry.UpdateMCPServer,
			readMCPServer:           ports.Registry.ReadMCPServer,
			listMCPServers:          ports.Registry.ListMCPServers,
			listMCPServerTools:      ports.Registry.ListMCPServerTools,
			listMCPServerResources:  ports.Registry.ListMCPServerResources,
			listMCPServerPrompts:    ports.Registry.ListMCPServerPrompts,
			createMCPCapability:     ports.Registry.CreateMCPCapability,
			updateMCPCapability:     ports.Registry.UpdateMCPCapability,
			readMCPCapability:       ports.Registry.ReadMCPCapability,
			listMCPCapabilities:     ports.Registry.ListMCPCapabilities,
		},
		memoryOperations: memoryOperations{
			createMemoryItem:       ports.Memory.CreateMemoryItem,
			readMemoryItem:         ports.Memory.ReadMemoryItem,
			updateMemoryItem:       ports.Memory.UpdateMemoryItem,
			deleteMemoryItem:       ports.Memory.DeleteMemoryItem,
			listMemoryByWorkspace:  ports.Memory.ListMemoryByWorkspace,
			searchMemory:           ports.Memory.SearchMemory,
			listMemoryRecallTraces: ports.Memory.ListMemoryRecallTraces,
		},
		configurationOperations: configurationOperations{
			readConfiguration:            ports.Configuration.ReadConfiguration,
			updateServerConfiguration:    ports.Configuration.UpdateServerConfiguration,
			updateRuntimeConfiguration:   ports.Configuration.UpdateRuntimeConfiguration,
			updateLLMConfiguration:       ports.Configuration.UpdateLLMConfiguration,
			getLLMModelCatalog:           ports.Configuration.GetLLMModelCatalog,
			refreshLLMModelCatalog:       ports.Configuration.RefreshLLMModelCatalog,
			readConfigurationWithCatalog: ports.Configuration.ReadConfigurationWithCatalog,
			updateWebSearchConfiguration: ports.Configuration.UpdateWebSearchConfiguration,
		},
	}
}
